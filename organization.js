(() => {
  const nodes = document.querySelectorAll(".organization-node");
  const nodeGroup = document.querySelector(".organization-nodes");
  const reveal = document.getElementById("organizationReveal");
  const revealTitle = document.getElementById("organizationRevealTitle");
  const revealText = document.getElementById("organizationRevealText");
  const revealRoute = document.getElementById("organizationRevealRoute");

  if (!nodes.length || !nodeGroup || !reveal) return;

  function activateNode(node) {
    nodes.forEach((item) => {
      const active = item === node;
      item.classList.toggle("is-active", active);
      item.setAttribute("aria-pressed", active ? "true" : "false");
    });

    nodeGroup.classList.add("has-active");

    revealTitle.textContent = node.dataset.title || "";
    revealText.textContent = node.dataset.context || "";
    revealRoute.href = node.dataset.route || "#";
    revealRoute.textContent = node.dataset.action || "Explore";

    reveal.classList.add("is-visible");
    reveal.scrollIntoView({
      behavior: "smooth",
      block: "nearest"
    });
  }

  nodes.forEach((node) => {
    node.addEventListener("click", () => activateNode(node));
  });
})();
